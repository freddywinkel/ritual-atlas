import type { CardInterpretation } from "./types";

type KeywordTriplet = readonly [string, string, string];
type Perspective = CardInterpretation["combined"];

function perspective(
  enKeywords: KeywordTriplet,
  nlKeywords: KeywordTriplet,
  uprightEn: string,
  uprightNl: string,
  reversedEn: string,
  reversedNl: string,
  reflectionEn: string,
  reflectionNl: string,
): Perspective {
  return {
    keywords: { en: enKeywords, nl: nlKeywords },
    upright: { en: uprightEn, nl: uprightNl },
    reversed: { en: reversedEn, nl: reversedNl },
    reflection: { en: reflectionEn, nl: reflectionNl },
  };
}

